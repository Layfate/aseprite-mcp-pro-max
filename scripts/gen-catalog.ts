// Regenerates docs/catalog.json, docs/operations.md and docs/tools.md.
// Usage: npm run build && npx vitest run && npx tsx scripts/gen-catalog.ts
// Test levels come from tests/.coverage/*.txt, which the integration suites write
// (one op id per executed call). Run the tests first or every op shows "untested".
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { z } from "zod";
import { CATALOG, argSchema, compactSchema } from "../src/catalog/registry.js";
import { AREAS } from "../src/catalog/types.js";
import { startClient } from "../tests/helpers/client.js";

type Schema = {
  type?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  description?: string;
  items?: Schema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
};

/** Suites whose tests assert on results; "smoke" only checks that the example runs. */
const BEHAVIOR_SUITES = new Set(["behavior", "workflows", "legacy"]);
const covDir = path.resolve("tests/.coverage");
const suites: Record<string, Set<string>> = {};
if (existsSync(covDir)) {
  for (const f of readdirSync(covDir).filter((n) => n.endsWith(".txt"))) {
    suites[f.slice(0, -4)] = new Set(readFileSync(path.join(covDir, f), "utf8").split(/\r?\n/).filter(Boolean));
  }
}

const level = (tests: string[]) =>
  tests.some((t) => BEHAVIOR_SUITES.has(t)) ? "behavior" : tests.includes("smoke") ? "smoke" : "untested";

const entries = CATALOG.map((d) => {
  const tests = Object.keys(suites).filter((s) => suites[s]!.has(d.id)).sort();
  return {
    id: d.id,
    area: d.area,
    kind: d.kind,
    summary: d.summary,
    doc: d.doc,
    schema: compactSchema(z.toJSONSchema(argSchema(d), { io: "input", unrepresentable: "any" })) as Schema,
    example: d.example.args,
    requires: d.requires,
    status: d.status,
    live: d.live,
    slow: d.slow ?? false,
    notes: d.notes,
    tests,
    tested: level(tests),
  };
});

const counts = { behavior: 0, smoke: 0, untested: 0 } as Record<string, number>;
for (const e of entries) counts[e.tested]!++;
writeFileSync("docs/catalog.json", JSON.stringify({ generated: "scripts/gen-catalog.ts", total: entries.length, testLevels: counts, ops: entries }, null, 1) + "\n");

// ---- operations.md
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const typeOf = (s: Schema): string => {
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(" | ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.type === "array") return `${s.items ? typeOf(s.items) : "any"}[]`;
  if (s.type === "object" && !s.properties) return "object";
  if (s.type === "object") return "{…}";
  return s.type ?? "any";
};
const sig = (s: Schema) =>
  Object.entries(s.properties ?? {}).map(([k, v]) => `${k}${s.required?.includes(k) ? "" : "?"}: ${typeOf(v)}`).join(", ");
const badge = { behavior: "✔ behavior", smoke: "◐ smoke", untested: "○ untested" } as Record<string, string>;

const md: string[] = [
  "# Operation catalog",
  "",
  "_Generated by `scripts/gen-catalog.ts`. Do not edit by hand. Machine-readable: [catalog.json](catalog.json)._",
  "",
  `${entries.length} operations. Call any of them with \`run_op\` or inside \`batch\`; use \`search_ops\` / \`describe_ops\` to discover them at run time.`,
  "",
  "Test level: **✔ behavior** = asserted by the behavior, workflow or v1-compat suites; **◐ smoke** = the catalog example runs without error; **○ untested** = needs the live editor or an external provider.",
  "",
  `Totals: ${counts.behavior} behavior, ${counts.smoke} smoke-only, ${counts.untested} untested.`,
  "",
  "| Area | Ops |",
  "|---|---|",
];
for (const a of AREAS) {
  const n = entries.filter((e) => e.area === a).length;
  if (n) md.push(`| [${a}](#${a}) | ${n} |`);
}
md.push("");
for (const a of AREAS) {
  const list = entries.filter((e) => e.area === a);
  if (!list.length) continue;
  md.push(`## ${a}`, "", "| Op | Kind | Summary | Args | Tests |", "|---|---|---|---|---|");
  for (const e of list) {
    const flags = [e.live ? "live" : "", e.status !== "stable" ? e.status : "", e.slow ? "slow" : "", ...e.requires.filter((r) => r !== "aseprite" && r !== "node")]
      .filter(Boolean)
      .join(", ");
    md.push(`| \`${e.id}\` | ${e.kind} | ${cell(e.summary)}${flags ? ` _(${flags})_` : ""} | \`${cell(sig(e.schema)) || "—"}\` | ${badge[e.tested]} |`);
  }
  md.push("");
}
writeFileSync("docs/operations.md", md.join("\n"));

// ---- tools.md (from the running server, default and legacy profiles)
const tools: string[] = [
  "# Tool reference",
  "",
  "_Generated by `scripts/gen-catalog.ts` from the server's tool list. Do not edit by hand._",
  "",
  "The default `core` profile exposes the tools below; every operation is reached through them (see [operations.md](operations.md)).",
  "",
];
for (const [title, profile] of [["Core profile (default)", "core"], ["Legacy profile (v1-compatible names)", "legacy"]] as const) {
  const c = await startClient({ ASEPRITE_MCP_PROFILE: profile });
  const { tools: list } = await c.client.listTools();
  await c.close();
  tools.push(`## ${title}`, "", `\`ASEPRITE_MCP_PROFILE=${profile}\` — ${list.length} tools.`, "");
  for (const t of list) {
    const s = t.inputSchema as Schema;
    tools.push(`### ${t.name}`, "", t.description ?? "", "");
    const props = Object.entries(s.properties ?? {});
    if (profile === "legacy" || !props.length) continue;
    tools.push("| Parameter | Type | Required | Description |", "|---|---|---|---|");
    for (const [name, p] of props) tools.push(`| \`${name}\` | ${cell(typeOf(p))} | ${s.required?.includes(name) ? "yes" : ""} | ${cell(p.description ?? "")} |`);
    tools.push("");
  }
}
writeFileSync("docs/tools.md", tools.join("\n"));

console.log(`wrote docs/catalog.json, docs/operations.md, docs/tools.md — ${entries.length} ops (${counts.behavior} behavior, ${counts.smoke} smoke, ${counts.untested} untested)`);
