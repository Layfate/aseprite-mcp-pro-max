"""Pygame sample: `python examples/engines/pygame/main.py` (needs `pip install pygame`).

assets/ is generated by `npx tsx examples/build-samples.ts` (engine.pygame).
"""
import os
import sys

import pygame

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "assets"))
from aseprite_sheet import SpriteSheet  # noqa: E402

TAGS = ["idle_e", "walk_e", "idle_w", "walk_w"]


def main():
    pygame.init()
    screen = pygame.display.set_mode((960, 540))
    canvas = pygame.Surface((320, 180))
    sheet = SpriteSheet(os.path.join(HERE, "assets", "hero.pygame.json"))
    anims = [sheet.animation(t) for t in TAGS]
    clock = pygame.time.Clock()
    while True:
        dt = clock.tick(60)
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                return
        canvas.fill((26, 28, 44))
        for i, anim in enumerate(anims):
            anim.update(dt)
            canvas.blit(*anim.blit_args((40 + i * 80, 100)))
        pygame.transform.scale(canvas, screen.get_size(), screen)
        pygame.display.flip()


if __name__ == "__main__":
    main()
