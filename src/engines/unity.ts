import type { AssetModel } from "./model.js";

/**
 * Unity 2D integration.
 *
 * Native path: Unity's official Aseprite Importer (package com.unity.2d.aseprite; 6.0.x for
 * Unity 6000.6, 1.1.x for 2021.3-6000.0) imports .aseprite files directly, generating sprites,
 * animation clips from tags and an Animator controller (importMode = AnimatedSprite). We copy the
 * file into Assets/ (overwriting in place, never touching its .meta, so GUIDs and references
 * survive re-export) and write a sidecar JSON that an AssetPostprocessor applies to the
 * AsepriteImporter (pixels per unit, point filtering, pivot, clip generation).
 *
 * Helper path (no importer package): PNG + JSON sheet, sliced through the Sprite Editor data
 * provider API (ISpriteEditorDataProvider), reusing existing spriteIDs by name so sprite
 * references survive re-slicing; clips and an Animator controller are created or updated in place.
 */

export const UNITY_IMPORTER_PACKAGE = "com.unity.2d.aseprite";

/** Package version that matches a Unity editor version (from the package registry metadata). */
export function importerVersionFor(unityVersion: string): string {
  const m = /^(\d+)\.(\d+)/.exec(unityVersion);
  if (!m) return "1.1.5";
  const major = Number(m[1]);
  const minor = Number(m[2]);
  if (major === 6000) {
    if (minor >= 7) return "7.0.2";
    if (minor === 6) return "6.0.0";
    if (minor === 5) return "5.0.3";
    if (minor === 4) return "4.0.2";
    if (minor <= 0) return "1.1.5";
    return "1.2.1";
  }
  if (major >= 7000) return "8.0.0";
  return "1.1.5";
}

export interface UnitySidecar {
  generator: string;
  pixelsPerUnit: number;
  filterPoint: boolean;
  importMode: "AnimatedSprite" | "SpriteSheet" | "TileSet";
  generateAnimationClips: boolean;
  generateModelPrefab: boolean;
  /** Normalized pivot (0..1, origin bottom-left) relative to the canvas. */
  pivot: { x: number; y: number };
  includeHiddenLayers: boolean;
}

export function unitySidecar(m: AssetModel, o: { pixelsPerUnit?: number; importMode?: UnitySidecar["importMode"] } = {}): UnitySidecar {
  return {
    generator: "aseprite-mcp-pro-max",
    pixelsPerUnit: o.pixelsPerUnit ?? Math.max(m.canvas.w, m.canvas.h, 1),
    filterPoint: true,
    importMode: o.importMode ?? (m.frames.length > 1 ? "AnimatedSprite" : "SpriteSheet"),
    generateAnimationClips: m.frames.length > 1,
    generateModelPrefab: true,
    pivot: { x: round4(m.pivot.x / Math.max(1, m.canvas.w)), y: round4(1 - m.pivot.y / Math.max(1, m.canvas.h)) },
    includeHiddenLayers: false,
  };
}

const round4 = (n: number) => Math.round(n * 10000) / 10000;

/** Editor script for the native path (applies sidecar settings to AsepriteImporter). */
export function asepriteImporterScript(): string {
  return `// Generated by aseprite-mcp-pro-max. Applies <file>.aseprite-mcp.json next to an
// .aseprite/.ase asset to Unity's Aseprite Importer (com.unity.2d.aseprite).
#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEditor.U2D.Aseprite;
using UnityEngine;

namespace AsepriteMcp
{
    [System.Serializable]
    class Sidecar
    {
        public float pixelsPerUnit = 100;
        public bool filterPoint = true;
        public string importMode = "AnimatedSprite";
        public bool generateAnimationClips = true;
        public bool generateModelPrefab = true;
        public Vector2 pivot = new Vector2(0.5f, 0f);
        public bool includeHiddenLayers = false;
    }

    class AsepriteMcpImportSettings : AssetPostprocessor
    {
        void OnPreprocessAsset()
        {
            if (!(assetImporter is AsepriteImporter importer)) return;
            var sidecarPath = assetPath + ".aseprite-mcp.json";
            if (!File.Exists(sidecarPath)) return;
            var s = JsonUtility.FromJson<Sidecar>(File.ReadAllText(sidecarPath));
            importer.spritePixelsPerUnit = s.pixelsPerUnit;
            if (s.filterPoint) importer.filterMode = FilterMode.Point;
            importer.mipmapEnabled = false;
            if (System.Enum.TryParse(s.importMode, out FileImportModes mode)) importer.importMode = mode;
            importer.generateAnimationClips = s.generateAnimationClips;
            importer.generateModelPrefab = s.generateModelPrefab;
            importer.includeHiddenLayers = s.includeHiddenLayers;
            importer.pivotAlignment = SpriteAlignment.Custom;
            importer.pivotSpace = PivotSpaces.Canvas;
            importer.customPivotPosition = s.pivot;
        }
    }
}
#endif
`;
}

export interface UnitySheetMeta {
  generator: string;
  image: string;
  pixelsPerUnit: number;
  sprites: Array<{ name: string; x: number; y: number; w: number; h: number; pivotX: number; pivotY: number }>;
  clips: Array<{ name: string; loop: boolean; frames: Array<{ sprite: string; timeMs: number }>; lengthMs: number }>;
}

/** Sheet metadata for the helper path. Unity rects have their origin at the bottom-left. */
export function unitySheetMeta(m: AssetModel, pixelsPerUnit?: number): UnitySheetMeta {
  const name = (i: number) => `${m.name}_${i}`;
  return {
    generator: "aseprite-mcp-pro-max",
    image: m.image,
    pixelsPerUnit: pixelsPerUnit ?? Math.max(m.canvas.w, m.canvas.h, 1),
    sprites: m.frames.map((f) => ({
      name: name(f.index),
      x: f.rect.x,
      y: m.atlas.h - f.rect.y - f.rect.h,
      w: f.rect.w,
      h: f.rect.h,
      // pivot relative to the trimmed rect, normalized, origin bottom-left
      pivotX: round4((m.pivot.x - f.source.x) / Math.max(1, f.rect.w)),
      pivotY: round4((f.source.y + f.source.h - m.pivot.y) / Math.max(1, f.rect.h)),
    })),
    clips: m.animations.map((a) => {
      let t = 0;
      const frames = a.sequence.map((i, k) => {
        const e = { sprite: name(i), timeMs: t };
        t += a.durationsMs[k]!;
        return e;
      });
      return { name: a.name, loop: a.loop, frames, lengthMs: t };
    }),
  };
}

/** Editor script for the helper path: slice, keep sprite IDs, create/update clips + controller. */
export function sheetImporterScript(): string {
  return `// Generated by aseprite-mcp-pro-max. Slices <sheet>.png using <sheet>.unity.json and
// creates/updates AnimationClips and an AnimatorController next to it.
// Requires the 2D Sprite package (com.unity.2d.sprite). Menu: Tools > Aseprite MCP > Import Sheets.
#if UNITY_EDITOR
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Animations;
using UnityEditor.U2D.Sprites;
using UnityEngine;

namespace AsepriteMcp
{
    [System.Serializable] class SpriteDef { public string name; public int x, y, w, h; public float pivotX, pivotY; }
    [System.Serializable] class FrameDef { public string sprite; public float timeMs; }
    [System.Serializable] class ClipDef { public string name; public bool loop; public FrameDef[] frames; public float lengthMs; }
    [System.Serializable] class SheetDef { public string image; public float pixelsPerUnit; public SpriteDef[] sprites; public ClipDef[] clips; }

    static class SheetImporter
    {
        [MenuItem("Tools/Aseprite MCP/Import Sheets")]
        static void ImportAll()
        {
            foreach (var guid in AssetDatabase.FindAssets("t:TextAsset"))
            {
                var path = AssetDatabase.GUIDToAssetPath(guid);
                if (path.EndsWith(".unity.json")) Import(path);
            }
        }

        public static void Import(string jsonPath)
        {
            var def = JsonUtility.FromJson<SheetDef>(File.ReadAllText(jsonPath));
            var dir = Path.GetDirectoryName(jsonPath).Replace('\\\\', '/');
            var texPath = dir + "/" + def.image;
            var importer = (TextureImporter)AssetImporter.GetAtPath(texPath);
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Multiple;
            importer.filterMode = FilterMode.Point;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            importer.mipmapEnabled = false;
            importer.spritePixelsPerUnit = def.pixelsPerUnit;

            var factory = new SpriteDataProviderFactories();
            factory.Init();
            var provider = factory.GetSpriteEditorDataProviderFromObject(importer);
            provider.InitSpriteEditorDataProvider();
            // Keep existing spriteIDs by name so references to the sprites survive re-export.
            var existing = provider.GetSpriteRects().ToDictionary(r => r.name, r => r.spriteID);
            var rects = def.sprites.Select(s => new SpriteRect
            {
                name = s.name,
                rect = new Rect(s.x, s.y, s.w, s.h),
                alignment = SpriteAlignment.Custom,
                pivot = new Vector2(s.pivotX, s.pivotY),
                spriteID = existing.TryGetValue(s.name, out var id) ? id : GUID.Generate(),
            }).ToArray();
            provider.SetSpriteRects(rects);
            var names = provider.GetDataProvider<ISpriteNameFileIdDataProvider>();
            names?.SetNameFileIdPairs(rects.Select(r => new SpriteNameFileIdPair(r.name, r.spriteID)));
            provider.Apply();
            importer.SaveAndReimport();

            var sprites = AssetDatabase.LoadAllAssetsAtPath(texPath).OfType<Sprite>().ToDictionary(s => s.name);
            var controllerPath = dir + "/" + Path.GetFileNameWithoutExtension(def.image) + ".controller";
            var controller = AssetDatabase.LoadAssetAtPath<AnimatorController>(controllerPath) ?? AnimatorController.CreateAnimatorControllerAtPath(controllerPath);
            foreach (var c in def.clips)
            {
                var clipPath = dir + "/" + Path.GetFileNameWithoutExtension(def.image) + "_" + c.name + ".anim";
                var clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath);
                var isNew = clip == null;
                if (isNew) clip = new AnimationClip();
                var binding = EditorCurveBinding.PPtrCurve("", typeof(SpriteRenderer), "m_Sprite");
                var keys = c.frames.Select(f => new ObjectReferenceKeyframe { time = f.timeMs / 1000f, value = sprites[f.sprite] }).ToList();
                keys.Add(new ObjectReferenceKeyframe { time = c.lengthMs / 1000f, value = sprites[c.frames[c.frames.Length - 1].sprite] });
                AnimationUtility.SetObjectReferenceCurve(clip, binding, keys.ToArray());
                var settings = AnimationUtility.GetAnimationClipSettings(clip);
                settings.loopTime = c.loop;
                AnimationUtility.SetAnimationClipSettings(clip, settings);
                if (isNew)
                {
                    AssetDatabase.CreateAsset(clip, clipPath);
                    controller.AddMotion(clip);
                }
                else EditorUtility.SetDirty(clip);
            }
            AssetDatabase.SaveAssets();
        }
    }
}
#endif
`;
}

/** Batch-mode validation entry point for CI (Unity -batchmode -executeMethod AsepriteMcp.Validate.Run). */
export function validationScript(): string {
  return `#if UNITY_EDITOR
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

namespace AsepriteMcp
{
    public static class Validate
    {
        public static void Run()
        {
            var report = new System.Text.StringBuilder();
            foreach (var guid in AssetDatabase.FindAssets("", new[] { "Assets" }))
            {
                var path = AssetDatabase.GUIDToAssetPath(guid);
                if (!(path.EndsWith(".aseprite") || path.EndsWith(".ase") || path.EndsWith(".png"))) continue;
                var sprites = AssetDatabase.LoadAllAssetsAtPath(path).OfType<Sprite>().Count();
                var clips = AssetDatabase.LoadAllAssetsAtPath(path).OfType<AnimationClip>().Count();
                report.AppendLine($"{path}\\tguid={guid}\\tsprites={sprites}\\tclips={clips}");
            }
            File.WriteAllText("aseprite-mcp-unity-report.txt", report.ToString());
            EditorApplication.Exit(0);
        }
    }
}
#endif
`;
}
