/**
 * Text formats for engines without a native Aseprite importer.
 * Sources (checked 2026-11): PixiJS Spritesheet docs (frames/animations/meta, anchor),
 * Phaser AnimationManager.fromJSON + load.aseprite (needs "{frame}" filenames),
 * GameMaker manual "Strip Images" ("_stripN" suffix), Defold atlas_ddf.proto
 * (images/animations/playback/fps/extrude_borders), Cocos Creator atlas docs (Cocos2d-x plist,
 * TexturePacker 4 format), LÖVE love.graphics.newQuad, pygame Surface.subsurface.
 */

const frameKey = (m: AssetModel, i: number) => `${m.name}_${i}`;

// ---------------------------------------------------------------- Phaser 3

/** Phaser animation JSON for `this.anims.fromJSON()` (works with an atlas loaded via load.atlas or load.aseprite). */
export function phaserAnims(m: AssetModel, textureKey: string): unknown {
  return {
    anims: m.animations.map((a) => {
      const uniform = new Set(a.durationsMs).size === 1;
      return {
        key: a.name,
        type: "frame",
        frames: a.sequence.map((i, k) => ({ key: textureKey, frame: String(i), ...(uniform ? {} : { duration: a.durationsMs[k] }) })),
        frameRate: uniform ? Math.round((1000 / a.durationsMs[0]!) * 1000) / 1000 : undefined,
        duration: uniform ? undefined : 0,
        repeat: a.loop ? -1 : Math.max(0, a.repeats - 1),
        yoyo: false,
      };
    }),
  };
}

export function phaserLoader(m: AssetModel, textureKey: string, image: string, atlas: string, anims: string): string {
  return `// Phaser 3 usage (generated by aseprite-mcp-pro-max)
function preload() {
  this.load.aseprite(${JSON.stringify(textureKey)}, ${JSON.stringify(image)}, ${JSON.stringify(atlas)});
}
function create() {
  // Either create animations from the Aseprite tags...
  this.anims.createFromAseprite(${JSON.stringify(textureKey)});
  // ...or from the exported definitions (exact per-frame durations):
  // this.load.json('anims', ${JSON.stringify(anims)}); this.anims.fromJSON(this.cache.json.get('anims'));
  const sprite = this.add.sprite(100, 100, ${JSON.stringify(textureKey)}).setOrigin(${(m.pivot.x / Math.max(1, m.canvas.w)).toFixed(4)}, ${(m.pivot.y / Math.max(1, m.canvas.h)).toFixed(4)});
  sprite.play(${JSON.stringify(m.animations[0]?.name ?? "default")});
}
`;
}

// ---------------------------------------------------------------- PixiJS

export function pixiSpritesheet(m: AssetModel): unknown {
  const anchor = (f: AssetModel["frames"][number]) => ({
    x: Math.round(((m.pivot.x - f.source.x) / Math.max(1, f.rect.w)) * 10000) / 10000,
    y: Math.round(((m.pivot.y - f.source.y) / Math.max(1, f.rect.h)) * 10000) / 10000,
  });
  return {
    frames: Object.fromEntries(
      m.frames.map((f) => [
        frameKey(m, f.index),
        {
          frame: { x: f.rect.x, y: f.rect.y, w: f.rect.w, h: f.rect.h },
          rotated: false,
          trimmed: f.trimmed,
          spriteSourceSize: { x: f.source.x, y: f.source.y, w: f.source.w, h: f.source.h },
          sourceSize: { w: m.canvas.w, h: m.canvas.h },
          anchor: anchor(f),
          duration: f.durationMs,
        },
      ]),
    ),
    animations: Object.fromEntries(m.animations.map((a) => [a.name, a.sequence.map((i) => frameKey(m, i))])),
    meta: { app: "aseprite-mcp-pro-max", image: m.image, format: "RGBA8888", size: { w: m.atlas.w, h: m.atlas.h }, scale: "1" },
  };
}

// ---------------------------------------------------------------- GameMaker

/** GameMaker imports "<name>_strip<N>.png" as an N-frame sprite (one strip per tag). */
export function gamemakerStripName(base: string, anim: string, frames: number): string {
  return `${base}_${anim.replace(/[^A-Za-z0-9_]/g, "_")}_strip${frames}.png`;
}

export function gamemakerNotes(m: AssetModel, strips: Array<{ file: string; anim: string; frames: number; fps: number }>): unknown {
  return {
    generator: "aseprite-mcp-pro-max",
    note: "Import each *_stripN.png into GameMaker (Sprite Editor > Import); set the origin and speed below.",
    origin: { x: m.pivot.x, y: m.pivot.y },
    sprites: strips.map((s) => ({ ...s, speedType: "frames per second" })),
    varyingDurations: m.animations.filter((a) => new Set(a.durationsMs).size > 1).map((a) => ({ anim: a.name, durationsMs: a.durationsMs })),
  };
}

// ---------------------------------------------------------------- Defold

const DEFOLD_PLAYBACK: Record<string, [string, string]> = {
  forward: ["PLAYBACK_LOOP_FORWARD", "PLAYBACK_ONCE_FORWARD"],
  reverse: ["PLAYBACK_LOOP_BACKWARD", "PLAYBACK_ONCE_BACKWARD"],
  pingpong: ["PLAYBACK_LOOP_PINGPONG", "PLAYBACK_ONCE_PINGPONG"],
  pingpong_reverse: ["PLAYBACK_LOOP_PINGPONG", "PLAYBACK_ONCE_PINGPONG"],
};

/** Defold .atlas (protobuf text) referencing per-frame PNGs under `imageDir` (project path, starts with '/'). */
export function defoldAtlas(m: AssetModel, imageDir: string, frameFile: (i: number) => string, extrude = 1): { text: string; warnings: string[] } {
  const warnings: string[] = [];
  const dir = imageDir.replace(/\/+$/, "");
  const lines: string[] = [];
  for (const f of m.frames) lines.push("images {", `  image: "${dir}/${frameFile(f.index)}"`, "  sprite_trim_mode: SPRITE_TRIM_MODE_OFF", "}");
  for (const a of m.animations) {
    const step = gcdMs(a.durationsMs);
    const fps = Math.max(1, Math.round(1000 / step));
    if (Math.abs(1000 / fps - step) > 0.5) warnings.push(`'${a.name}': ${step} ms steps are approximated at ${fps} fps`);
    // Defold plays one fps per animation; longer frames are repeated to keep their timing.
    const seq = a.direction === "pingpong" || a.direction === "pingpong_reverse" ? a.frames : a.sequence;
    lines.push("animations {", `  id: "${a.name.replace(/"/g, "")}"`);
    seq.forEach((i) => {
      const d = m.frames[i]!.durationMs;
      const reps = Math.max(1, Math.round(d / step));
      for (let r = 0; r < reps; r++) lines.push("  images {", `    image: "${dir}/${frameFile(i)}"`, "  }");
    });
    const [loop, once] = DEFOLD_PLAYBACK[a.direction]!;
    lines.push(`  playback: ${a.loop ? loop : once}`, `  fps: ${fps}`, "  flip_horizontal: 0", "  flip_vertical: 0", "}");
  }
  lines.push("margin: 0", `extrude_borders: ${extrude}`, "inner_padding: 0", "");
  return { text: lines.join("\n"), warnings };
}

// ---------------------------------------------------------------- Cocos Creator (Cocos2d-x plist, format 3)

export function cocosPlist(m: AssetModel): string {
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const frames = m.frames
    .map((f) => {
      // offset of the trimmed rect's center from the original center, y up
      const ox = f.source.x + f.source.w / 2 - m.canvas.w / 2;
      const oy = m.canvas.h / 2 - (f.source.y + f.source.h / 2);
      return [
        `      <key>${esc(frameKey(m, f.index))}.png</key>`,
        "      <dict>",
        "        <key>aliases</key><array/>",
        `        <key>spriteOffset</key><string>{${ox},${oy}}</string>`,
        `        <key>spriteSize</key><string>{${f.rect.w},${f.rect.h}}</string>`,
        `        <key>spriteSourceSize</key><string>{${m.canvas.w},${m.canvas.h}}</string>`,
        `        <key>textureRect</key><string>{{${f.rect.x},${f.rect.y}},{${f.rect.w},${f.rect.h}}}</string>`,
        "        <key>textureRotated</key><false/>",
        "      </dict>",
      ].join("\n");
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
  <dict>
    <key>frames</key>
    <dict>
${frames}
    </dict>
    <key>metadata</key>
    <dict>
      <key>format</key><integer>3</integer>
      <key>pixelFormat</key><string>RGBA8888</string>
      <key>premultiplyAlpha</key><false/>
      <key>realTextureFileName</key><string>${esc(m.image)}</string>
      <key>size</key><string>{${m.atlas.w},${m.atlas.h}}</string>
      <key>textureFileName</key><string>${esc(m.image)}</string>
    </dict>
  </dict>
</plist>
`;
}

export function cocosAnimations(m: AssetModel): unknown {
  return {
    generator: "aseprite-mcp-pro-max",
    note: "SpriteFrame names refer to the plist atlas; build AnimationClips with AnimationClip.createWithSpriteFrames or the Animation editor.",
    animations: m.animations.map((a) => ({ name: a.name, loop: a.loop, frames: a.sequence.map((i) => `${frameKey(m, i)}.png`), durationsMs: a.durationsMs })),
    pivot: { x: m.pivot.x / Math.max(1, m.canvas.w), y: 1 - m.pivot.y / Math.max(1, m.canvas.h) },
  };
}

// ---------------------------------------------------------------- LÖVE (Lua module)

export function loveModule(m: AssetModel): string {
  const lua = (s: string) => `"${s.replace(/[\\"]/g, (c) => `\\${c}`)}"`;
  const frames = m.frames.map((f) => `    { x = ${f.rect.x}, y = ${f.rect.y}, w = ${f.rect.w}, h = ${f.rect.h}, ox = ${f.source.x}, oy = ${f.source.y}, ms = ${f.durationMs} },`).join("\n");
  const anims = m.animations
    .map((a) => `    [${lua(a.name)}] = { loop = ${a.loop}, frames = { ${a.sequence.map((i) => i + 1).join(", ")} }, ms = { ${a.durationsMs.join(", ")} } },`)
    .join("\n");
  return `-- Generated by aseprite-mcp-pro-max. Usage:
--   local sheet = require(${lua(m.name)})
--   local anim = sheet.new(love.graphics.newImage(sheet.image))
--   function love.update(dt) anim:update(dt) end
--   function love.draw() anim:draw("${m.animations[0]?.name ?? "default"}", 100, 100) end
local M = {
  image = ${lua(m.image)},
  width = ${m.canvas.w}, height = ${m.canvas.h},
  pivot = { x = ${m.pivot.x}, y = ${m.pivot.y} },
  frames = {
${frames}
  },
  animations = {
${anims}
  },
}

function M.new(image)
  local self = { image = image, quads = {}, time = 0 }
  local iw, ih = image:getDimensions()
  for i, f in ipairs(M.frames) do self.quads[i] = love.graphics.newQuad(f.x, f.y, f.w, f.h, iw, ih) end
  image:setFilter("nearest", "nearest")
  function self:update(dt) self.time = self.time + dt * 1000 end
  function self:frameAt(name)
    local a = M.animations[name]
    local total = 0
    for _, ms in ipairs(a.ms) do total = total + ms end
    local t = a.loop and (self.time % total) or math.min(self.time, total - 1)
    for k, ms in ipairs(a.ms) do
      if t < ms then return a.frames[k] end
      t = t - ms
    end
    return a.frames[#a.frames]
  end
  function self:draw(name, x, y)
    local i = self:frameAt(name)
    local f = M.frames[i]
    love.graphics.draw(self.image, self.quads[i], x + f.ox - M.pivot.x, y + f.oy - M.pivot.y)
  end
  return self
end

return M
`;
}

// ---------------------------------------------------------------- Pygame (JSON + loader)

export function pygameData(m: AssetModel): unknown {
  return {
    generator: "aseprite-mcp-pro-max",
    image: m.image,
    canvas: m.canvas,
    pivot: m.pivot,
    frames: m.frames.map((f) => ({ rect: [f.rect.x, f.rect.y, f.rect.w, f.rect.h], offset: [f.source.x, f.source.y], ms: f.durationMs })),
    animations: Object.fromEntries(m.animations.map((a) => [a.name, { loop: a.loop, frames: a.sequence, ms: a.durationsMs }])),
  };
}

export function pygameLoader(): string {
  return `"""Generated by aseprite-mcp-pro-max: load a sprite sheet + JSON exported for pygame.

    sheet = SpriteSheet("hero.pygame.json")
    anim = sheet.animation("walk")
    anim.update(dt_ms); screen.blit(*anim.blit_args((100, 100)))
"""
import json
import os

import pygame


class SpriteSheet:
    def __init__(self, json_path):
        with open(json_path, "r", encoding="utf-8") as f:
            self.data = json.load(f)
        image = os.path.join(os.path.dirname(json_path), self.data["image"])
        self.image = pygame.image.load(image)
        self.frames = [self.image.subsurface(pygame.Rect(*fr["rect"])) for fr in self.data["frames"]]

    def animation(self, name):
        return Animation(self, self.data["animations"][name])


class Animation:
    def __init__(self, sheet, spec):
        self.sheet, self.spec, self.time = sheet, spec, 0

    def update(self, dt_ms):
        self.time += dt_ms

    def frame_index(self):
        total = sum(self.spec["ms"])
        t = self.time % total if self.spec["loop"] else min(self.time, total - 1)
        for i, ms in enumerate(self.spec["ms"]):
            if t < ms:
                return self.spec["frames"][i]
            t -= ms
        return self.spec["frames"][-1]

    def blit_args(self, pos):
        i = self.frame_index()
        fr = self.sheet.data["frames"][i]
        piv = self.sheet.data["pivot"]
        return self.sheet.frames[i], (pos[0] + fr["offset"][0] - piv["x"], pos[1] + fr["offset"][1] - piv["y"])
`;
}
